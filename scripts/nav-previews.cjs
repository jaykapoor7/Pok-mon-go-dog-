/* Captures the small page previews shown in the site menus (src/components/site/SiteHeader.tsx): every page the
   Platform, Solutions and Resources menus link to, as it renders, at 1440×900 without the site header, scaled to
   480×300. Run against a local production build of the public site (not a demo build):

     node scripts/nav-previews.cjs http://localhost:3100

   Writes public/nav/<slug>.webp and src/components/site/nav-shots.ts (the list of previews that exist). Re-run when a
   linked page changes enough that its preview no longer matches. */
const { chromium } = require("playwright");
const sharp = require("sharp");
const fs = require("fs");
const path = require("path");

const base = process.argv[2] || "http://localhost:3100";
const root = path.join(__dirname, "..");
const src = fs.readFileSync(path.join(root, "src/sp3/site/nav-data.tsx"), "utf8");
const block = src.slice(src.indexOf("export const MEGA"));
const hrefs = [...new Set([...block.matchAll(/href: "([^"]+)"/g)].map((m) => m[1]))].filter((h) => h.startsWith("/") && !h.startsWith("/talk"));
const slug = (h) => h.replace(/^\//, "").replace(/[^a-z0-9]+/gi, "-").replace(/^-|-$/g, "").toLowerCase() || "home";

(async () => {
  const outDir = path.join(root, "public/nav");
  fs.mkdirSync(outDir, { recursive: true });
  const b = await chromium.launch();
  const c = await b.newContext({ viewport: { width: 1440, height: 900 }, reducedMotion: "reduce" });
  await c.addInitScript(() => { try { localStorage.setItem("straypaw.notice.storage.v1", "1"); localStorage.setItem("sp.welcome.first-workflow", "1"); } catch { /* fine */ } });
  const pg = await c.newPage();
  const done = {};
  for (const h of hrefs) {
    const s = slug(h);
    try {
      const res = await pg.goto(base + h, { waitUntil: "networkidle", timeout: 60000 });
      if (res && res.status() >= 400) { console.log("skip", h, res.status()); continue; }
      await pg.addStyleTag({ content: "header.s4-nav, .s4-announce, .s7-welcome, .sp-storage-notice, [class*='storage-notice'] { display: none !important; } html { scroll-behavior: auto !important; }" });
      const hash = h.split("#")[1];
      await pg.evaluate((id) => { const el = id ? document.getElementById(id) : null; if (el) window.scrollTo(0, el.getBoundingClientRect().top + window.scrollY - 24); else window.scrollTo(0, 0); }, hash || null);
      await pg.waitForTimeout(900);
      const png = await pg.screenshot();
      await sharp(png).resize(480, 300).webp({ quality: 72 }).toFile(path.join(outDir, `${s}.webp`));
      done[h] = `/nav/${s}.webp`;
      console.log("ok", h);
    } catch (e) { console.log("fail", h, e.message.split("\n")[0]); }
  }
  await b.close();
  const lines = Object.entries(done).map(([h, f]) => `  ${JSON.stringify(h)}: ${JSON.stringify(f)},`).join("\n");
  fs.writeFileSync(path.join(root, "src/components/site/nav-shots.ts"),
    `/* Generated by scripts/nav-previews.cjs: a 480×300 preview of each page the site menus link to, captured from the\n   page itself. Shown beside the menu while a link is pointed at or focused. */\nexport const NAV_SHOTS: Record<string, string> = {\n${lines}\n};\n`);
})();
