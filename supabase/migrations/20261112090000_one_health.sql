-- One Health programme foundation (BeST Bengaluru and future programmes).
--
-- Additive only. New tables and functions; nothing existing is altered or
-- dropped. Staging first; production needs the owner's explicit approval.
--
-- Shape
--   oh_programmes      a city programme (e.g. Bengaluru rabies elimination)
--   oh_institutions    who takes part: coordinator, municipal division,
--                      hospital / anti-rabies clinic, laboratory, NGO, research
--   oh_members         people in an institution, with a programme role.
--                      NGO staff are NOT duplicated here: an institution of
--                      kind 'ngo' points at an existing organisation and its
--                      ngo_members are its people.
--   oh_ward_assignments which NGO answers animal follow-ups in which ward
--   oh_service_status  verified availability of services at facilities
--                      (append-only; stale = not verified). No stock counts.
--   oh_handoffs        work passed between institutions. Never carries
--                      patient data.
--   oh_samples (+events) animal samples and chain of custody; results are
--                      entered only by the receiving laboratory.
--   oh_ward_estimates  dog population estimates WITH method and source;
--                      coverage against the target is shown only where one
--                      exists.
--   oh_trainings       training sessions held for the programme.
--
--   health.*           human-health records (bite exposures, citizen bite
--                      notices, PEP courses and doses, reminder log, audit).
--                      The schema is not granted to anon or authenticated and
--                      is not exposed through the API; every read and write
--                      goes through the SECURITY DEFINER functions below,
--                      which check facility membership and clinical role.
--
-- Clinical governance
--   * StrayPaw never decides a treatment. A clinician records the exposure
--     category they assessed, the regimen they prescribed (free text, as
--     written in the facility's own protocol) and the dates they set for each
--     dose. No schedule is generated by the software.
--   * Only role 'clinician' may record the category or prescribe. Nurses
--     record doses given. Records staff register presentations and notices.
--   * Programme views see counts by ward and week only, and any count below
--     five is suppressed.

-- ── Programmes and institutions ─────────────────────────────────────────
CREATE TABLE IF NOT EXISTS public.oh_programmes (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  slug text NOT NULL UNIQUE CHECK (slug ~ '^[a-z0-9-]{3,60}$'),
  name text NOT NULL CHECK (length(name) BETWEEN 3 AND 140),
  city text NOT NULL,
  summary text CHECK (summary IS NULL OR length(summary) <= 600),
  status text NOT NULL DEFAULT 'pilot' CHECK (status IN ('planning', 'pilot', 'active', 'closed')),
  -- The programme's stated dog vaccination coverage target (BeST: at least 70%).
  vaccination_target numeric NOT NULL DEFAULT 0.70 CHECK (vaccination_target > 0 AND vaccination_target <= 1),
  wards text[] NOT NULL DEFAULT '{}',
  -- Dates ("today", "due", "overdue") are the programme's local dates, never the server's.
  time_zone text NOT NULL DEFAULT 'Asia/Kolkata',
  illustrative boolean NOT NULL DEFAULT false,   -- demonstration data, always labelled in the app
  created_at timestamptz NOT NULL DEFAULT now()
);

ALTER TABLE public.oh_programmes ADD COLUMN IF NOT EXISTS time_zone text NOT NULL DEFAULT 'Asia/Kolkata';

CREATE TABLE IF NOT EXISTS public.oh_institutions (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  programme_id uuid NOT NULL REFERENCES public.oh_programmes(id) ON DELETE CASCADE,
  kind text NOT NULL CHECK (kind IN ('coordinator', 'municipal', 'hospital', 'clinic', 'laboratory', 'ngo', 'research', 'training')),
  name text NOT NULL CHECK (length(name) BETWEEN 2 AND 160),
  short_name text CHECK (short_name IS NULL OR length(short_name) <= 40),
  ngo_id uuid REFERENCES public.ngos(id),
  responsibilities text CHECK (responsibilities IS NULL OR length(responsibilities) <= 400),
  ward text,
  address text CHECK (address IS NULL OR length(address) <= 300),
  phone text CHECK (phone IS NULL OR length(phone) <= 30),
  hours text CHECK (hours IS NULL OR length(hours) <= 120),
  lat double precision CHECK (lat IS NULL OR lat BETWEEN -90 AND 90),
  lng double precision CHECK (lng IS NULL OR lng BETWEEN -180 AND 180),
  listed_publicly boolean NOT NULL DEFAULT false,  -- facilities shown in the citizen finder
  created_at timestamptz NOT NULL DEFAULT now(),
  CHECK (kind <> 'ngo' OR ngo_id IS NOT NULL)
);
CREATE INDEX IF NOT EXISTS oh_institutions_programme ON public.oh_institutions (programme_id, kind);
CREATE UNIQUE INDEX IF NOT EXISTS oh_institutions_ngo ON public.oh_institutions (programme_id, ngo_id) WHERE ngo_id IS NOT NULL;

CREATE TABLE IF NOT EXISTS public.oh_members (
  institution_id uuid NOT NULL REFERENCES public.oh_institutions(id) ON DELETE CASCADE,
  user_id uuid NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  role text NOT NULL CHECK (role IN ('lead', 'coordinator', 'clinician', 'nurse', 'records', 'lab_scientist', 'analyst', 'field', 'trainer')),
  display_name text CHECK (display_name IS NULL OR length(display_name) <= 80),
  created_at timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (institution_id, user_id)
);
CREATE INDEX IF NOT EXISTS oh_members_user ON public.oh_members (user_id);

CREATE TABLE IF NOT EXISTS public.oh_ward_assignments (
  programme_id uuid NOT NULL REFERENCES public.oh_programmes(id) ON DELETE CASCADE,
  ward text NOT NULL,
  institution_id uuid NOT NULL REFERENCES public.oh_institutions(id) ON DELETE CASCADE,
  duty text NOT NULL DEFAULT 'animal_followup' CHECK (duty IN ('animal_followup', 'vaccination', 'sample_collection')),
  PRIMARY KEY (programme_id, ward, duty)
);

-- ── Membership helpers (SECURITY DEFINER: callers cannot read the tables they consult) ──
-- Every institution the caller belongs to, with their role there.
CREATE OR REPLACE FUNCTION public.oh_my_memberships()
RETURNS TABLE (institution_id uuid, programme_id uuid, kind text, role text)
LANGUAGE sql STABLE SECURITY DEFINER SET search_path = pg_catalog, public AS $$
  SELECT i.id, i.programme_id, i.kind, m.role
    FROM public.oh_members m JOIN public.oh_institutions i ON i.id = m.institution_id
   WHERE m.user_id = auth.uid()
  UNION
  SELECT i.id, i.programme_id, i.kind,
         CASE WHEN nm.role IN ('admin', 'coordinator') THEN 'coordinator' WHEN nm.role = 'veterinarian' THEN 'clinician' ELSE 'field' END
    FROM public.oh_institutions i JOIN public.ngo_members nm ON nm.ngo_id = i.ngo_id
   WHERE i.kind = 'ngo' AND nm.user_id = auth.uid()
$$;

CREATE OR REPLACE FUNCTION public.oh_role_in(p_institution uuid)
RETURNS text LANGUAGE sql STABLE SECURITY DEFINER SET search_path = pg_catalog, public AS $$
  SELECT role FROM public.oh_my_memberships() WHERE institution_id = p_institution
   ORDER BY CASE role WHEN 'lead' THEN 0 WHEN 'clinician' THEN 1 WHEN 'coordinator' THEN 2 ELSE 3 END LIMIT 1
$$;

-- Programme oversight: members of the coordinating or municipal institutions.
CREATE OR REPLACE FUNCTION public.oh_can_oversee(p_programme uuid)
RETURNS boolean LANGUAGE sql STABLE SECURITY DEFINER SET search_path = pg_catalog, public AS $$
  SELECT EXISTS (SELECT 1 FROM public.oh_my_memberships() WHERE programme_id = p_programme AND kind IN ('coordinator', 'municipal'))
$$;

CREATE OR REPLACE FUNCTION public.oh_in_programme(p_programme uuid)
RETURNS boolean LANGUAGE sql STABLE SECURITY DEFINER SET search_path = pg_catalog, public AS $$
  SELECT EXISTS (SELECT 1 FROM public.oh_my_memberships() WHERE programme_id = p_programme)
$$;

-- The programme's local date. Bengaluru is UTC+05:30, so the server's date is wrong for five and a half hours every night.
CREATE OR REPLACE FUNCTION public.oh_today(p_programme uuid)
RETURNS date LANGUAGE sql STABLE SECURITY DEFINER SET search_path = pg_catalog, public AS $$
  SELECT (now() AT TIME ZONE coalesce((SELECT time_zone FROM public.oh_programmes WHERE id = p_programme), 'Asia/Kolkata'))::date
$$;

-- ── Service availability (verified, expiring, append-only) ─────────────
CREATE TABLE IF NOT EXISTS public.oh_service_status (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  institution_id uuid NOT NULL REFERENCES public.oh_institutions(id) ON DELETE CASCADE,
  service text NOT NULL CHECK (service IN ('arv', 'rig', 'wound_care', 'dog_vaccination', 'rabies_testing')),
  status text NOT NULL CHECK (status IN ('available', 'limited', 'unavailable')),
  note text CHECK (note IS NULL OR length(note) <= 200),
  verified_by uuid REFERENCES auth.users(id),
  verified_by_name text,
  verified_at timestamptz NOT NULL DEFAULT now(),
  valid_until timestamptz NOT NULL,
  CHECK (valid_until > verified_at AND valid_until <= verified_at + interval '14 days')
);
CREATE INDEX IF NOT EXISTS oh_service_latest ON public.oh_service_status (institution_id, service, verified_at DESC);

-- ── Handoffs between institutions (no patient data, ever) ──────────────
CREATE TABLE IF NOT EXISTS public.oh_handoffs (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  programme_id uuid NOT NULL REFERENCES public.oh_programmes(id) ON DELETE CASCADE,
  kind text NOT NULL CHECK (kind IN ('animal_followup', 'sample_request', 'result_notice', 'service_gap', 'vaccination_request')),
  from_institution uuid REFERENCES public.oh_institutions(id),
  to_institution uuid NOT NULL REFERENCES public.oh_institutions(id),
  title text NOT NULL CHECK (length(title) BETWEEN 3 AND 160),
  detail text CHECK (detail IS NULL OR length(detail) <= 1200),
  ward text,
  place text CHECK (place IS NULL OR length(place) <= 200),
  animal_id uuid REFERENCES public.dogs(id) ON DELETE SET NULL,
  sample_id uuid,
  status text NOT NULL DEFAULT 'open' CHECK (status IN ('open', 'accepted', 'done', 'declined')),
  due_on date,
  outcome text CHECK (outcome IS NULL OR length(outcome) <= 600),
  created_by uuid REFERENCES auth.users(id),
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  closed_at timestamptz,
  closed_by_name text
);
CREATE INDEX IF NOT EXISTS oh_handoffs_to ON public.oh_handoffs (to_institution, status, created_at DESC);
CREATE INDEX IF NOT EXISTS oh_handoffs_programme ON public.oh_handoffs (programme_id, status);

-- ── Laboratory samples and chain of custody ────────────────────────────
CREATE TABLE IF NOT EXISTS public.oh_samples (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  programme_id uuid NOT NULL REFERENCES public.oh_programmes(id) ON DELETE CASCADE,
  code text NOT NULL UNIQUE,
  submitted_by uuid NOT NULL REFERENCES public.oh_institutions(id),
  laboratory_id uuid NOT NULL REFERENCES public.oh_institutions(id),
  animal_id uuid REFERENCES public.dogs(id) ON DELETE SET NULL,
  species text NOT NULL CHECK (species IN ('dog', 'cat', 'cattle', 'monkey', 'wildlife', 'other')),
  sample_type text NOT NULL CHECK (sample_type IN ('brain_tissue', 'saliva', 'csf', 'serum', 'other')),
  reason text CHECK (reason IS NULL OR length(reason) <= 400),
  collected_on date NOT NULL,
  collected_by_name text,
  ward text,
  place text CHECK (place IS NULL OR length(place) <= 200),
  status text NOT NULL DEFAULT 'collected' CHECK (status IN ('collected', 'dispatched', 'received', 'testing', 'resulted', 'rejected')),
  result text CHECK (result IS NULL OR result IN ('positive', 'negative', 'inconclusive')),
  method text CHECK (method IS NULL OR length(method) <= 120),
  result_note text CHECK (result_note IS NULL OR length(result_note) <= 600),
  resulted_at timestamptz,
  resulted_by_name text,
  created_at timestamptz NOT NULL DEFAULT now(),
  CHECK ((status = 'resulted') = (result IS NOT NULL))
);
CREATE INDEX IF NOT EXISTS oh_samples_lab ON public.oh_samples (laboratory_id, status, created_at DESC);
CREATE INDEX IF NOT EXISTS oh_samples_submitter ON public.oh_samples (submitted_by, created_at DESC);

CREATE TABLE IF NOT EXISTS public.oh_sample_events (
  id bigserial PRIMARY KEY,
  sample_id uuid NOT NULL REFERENCES public.oh_samples(id) ON DELETE CASCADE,
  at timestamptz NOT NULL DEFAULT now(),
  actor uuid REFERENCES auth.users(id),
  actor_name text,
  institution_id uuid REFERENCES public.oh_institutions(id),
  action text NOT NULL CHECK (action IN ('collected', 'dispatched', 'received', 'testing', 'resulted', 'rejected', 'note')),
  note text CHECK (note IS NULL OR length(note) <= 400)
);
CREATE INDEX IF NOT EXISTS oh_sample_events_sample ON public.oh_sample_events (sample_id, at);

