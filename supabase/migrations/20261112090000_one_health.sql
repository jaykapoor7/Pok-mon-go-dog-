-- ── RLS: programme tables are readable by programme participants; all writes go through functions ──
DO $$ DECLARE t text; BEGIN
  FOREACH t IN ARRAY ARRAY['oh_programmes','oh_institutions','oh_members','oh_ward_assignments','oh_service_status','oh_handoffs','oh_samples','oh_sample_events','oh_ward_estimates','oh_trainings'] LOOP
    EXECUTE format('ALTER TABLE public.%I ENABLE ROW LEVEL SECURITY', t);
    EXECUTE format('REVOKE ALL ON public.%I FROM anon, authenticated', t);
  END LOOP;
END $$;
GRANT SELECT ON public.oh_programmes, public.oh_institutions, public.oh_ward_assignments, public.oh_service_status, public.oh_ward_estimates, public.oh_trainings, public.oh_handoffs, public.oh_samples, public.oh_sample_events, public.oh_members TO authenticated;

DROP POLICY IF EXISTS oh_programmes_read ON public.oh_programmes;
CREATE POLICY oh_programmes_read ON public.oh_programmes FOR SELECT TO authenticated USING (public.oh_in_programme(id));
DROP POLICY IF EXISTS oh_institutions_read ON public.oh_institutions;
CREATE POLICY oh_institutions_read ON public.oh_institutions FOR SELECT TO authenticated USING (public.oh_in_programme(programme_id));
DROP POLICY IF EXISTS oh_members_read ON public.oh_members;
CREATE POLICY oh_members_read ON public.oh_members FOR SELECT TO authenticated USING (user_id = auth.uid() OR public.oh_role_in(institution_id) IN ('lead', 'coordinator'));
DROP POLICY IF EXISTS oh_wards_read ON public.oh_ward_assignments;
CREATE POLICY oh_wards_read ON public.oh_ward_assignments FOR SELECT TO authenticated USING (public.oh_in_programme(programme_id));
DROP POLICY IF EXISTS oh_service_read ON public.oh_service_status;
CREATE POLICY oh_service_read ON public.oh_service_status FOR SELECT TO authenticated USING (EXISTS (SELECT 1 FROM public.oh_institutions i WHERE i.id = institution_id AND public.oh_in_programme(i.programme_id)));
DROP POLICY IF EXISTS oh_estimates_read ON public.oh_ward_estimates;
CREATE POLICY oh_estimates_read ON public.oh_ward_estimates FOR SELECT TO authenticated USING (public.oh_in_programme(programme_id));
DROP POLICY IF EXISTS oh_trainings_read ON public.oh_trainings;
CREATE POLICY oh_trainings_read ON public.oh_trainings FOR SELECT TO authenticated USING (public.oh_in_programme(programme_id));
DROP POLICY IF EXISTS oh_handoffs_read ON public.oh_handoffs;
CREATE POLICY oh_handoffs_read ON public.oh_handoffs FOR SELECT TO authenticated USING (
  public.oh_role_in(to_institution) IS NOT NULL OR (from_institution IS NOT NULL AND public.oh_role_in(from_institution) IS NOT NULL) OR public.oh_can_oversee(programme_id));
DROP POLICY IF EXISTS oh_samples_read ON public.oh_samples;
CREATE POLICY oh_samples_read ON public.oh_samples FOR SELECT TO authenticated USING (
  public.oh_role_in(laboratory_id) IS NOT NULL OR public.oh_role_in(submitted_by) IS NOT NULL OR public.oh_can_oversee(programme_id));
DROP POLICY IF EXISTS oh_sample_events_read ON public.oh_sample_events;
CREATE POLICY oh_sample_events_read ON public.oh_sample_events FOR SELECT TO authenticated USING (
  EXISTS (SELECT 1 FROM public.oh_samples s WHERE s.id = sample_id AND (public.oh_role_in(s.laboratory_id) IS NOT NULL OR public.oh_role_in(s.submitted_by) IS NOT NULL OR public.oh_can_oversee(s.programme_id))));

-- ── Human-health schema: not exposed, not granted ──────────────────────
CREATE SCHEMA IF NOT EXISTS health;
REVOKE ALL ON SCHEMA health FROM PUBLIC;
DO $$ BEGIN EXECUTE 'REVOKE ALL ON SCHEMA health FROM anon, authenticated'; EXCEPTION WHEN undefined_object THEN NULL; END $$;

CREATE TABLE IF NOT EXISTS health.citizen_notices (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  programme_id uuid NOT NULL REFERENCES public.oh_programmes(id) ON DELETE CASCADE,
  facility_id uuid REFERENCES public.oh_institutions(id),
  happened_on date NOT NULL,
  ward text,
  place text CHECK (place IS NULL OR length(place) <= 200),
  animal_species text NOT NULL DEFAULT 'dog' CHECK (animal_species IN ('dog', 'cat', 'cattle', 'monkey', 'wildlife', 'other', 'unknown')),
  animal_description text CHECK (animal_description IS NULL OR length(animal_description) <= 300),
  callback_phone text CHECK (callback_phone IS NULL OR callback_phone ~ '^[0-9+ ]{8,16}$'),
  callback_consent boolean NOT NULL DEFAULT false,
  status text NOT NULL DEFAULT 'new' CHECK (status IN ('new', 'contacted', 'presented', 'closed')),
  created_at timestamptz NOT NULL DEFAULT now(),
  CHECK (callback_phone IS NULL OR callback_consent)
);

CREATE TABLE IF NOT EXISTS health.exposures (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  programme_id uuid NOT NULL REFERENCES public.oh_programmes(id) ON DELETE CASCADE,
  facility_id uuid NOT NULL REFERENCES public.oh_institutions(id),
  code text NOT NULL UNIQUE,
  patient_ref text CHECK (patient_ref IS NULL OR length(patient_ref) <= 40),  -- the facility's own register number; no names
  age_band text NOT NULL DEFAULT 'not_recorded' CHECK (age_band IN ('0-4', '5-14', '15-29', '30-49', '50+', 'not_recorded')),
  sex text NOT NULL DEFAULT 'not_recorded' CHECK (sex IN ('female', 'male', 'other', 'not_recorded')),
  ward text,
  exposure_on date NOT NULL,
  presented_on date NOT NULL,
  exposure_kind text NOT NULL CHECK (exposure_kind IN ('bite', 'scratch', 'lick_broken_skin', 'other')),
  -- The category the treating clinician assessed (WHO categories). Recorded, never derived.
  category text NOT NULL DEFAULT 'not_recorded' CHECK (category IN ('I', 'II', 'III', 'not_recorded')),
  category_by uuid REFERENCES auth.users(id),
  category_by_name text,
  animal_species text NOT NULL DEFAULT 'dog' CHECK (animal_species IN ('dog', 'cat', 'cattle', 'monkey', 'wildlife', 'other', 'unknown')),
  animal_ownership text NOT NULL DEFAULT 'unknown' CHECK (animal_ownership IN ('community', 'owned', 'unknown')),
  animal_description text CHECK (animal_description IS NULL OR length(animal_description) <= 300),
  animal_place text CHECK (animal_place IS NULL OR length(animal_place) <= 200),
  source text NOT NULL DEFAULT 'walk_in' CHECK (source IN ('walk_in', 'referral', 'citizen_notice')),
  notice_id uuid REFERENCES health.citizen_notices(id),
  contact_phone text CHECK (contact_phone IS NULL OR contact_phone ~ '^[0-9+ ]{8,16}$'),
  reminder_consent boolean NOT NULL DEFAULT false,
  handoff_id uuid,
  created_by uuid REFERENCES auth.users(id),
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CHECK (exposure_on <= presented_on),
  CHECK (contact_phone IS NULL OR reminder_consent)
);
CREATE INDEX IF NOT EXISTS health_exposures_facility ON health.exposures (facility_id, presented_on DESC);
CREATE INDEX IF NOT EXISTS health_exposures_programme ON health.exposures (programme_id, exposure_on);

CREATE TABLE IF NOT EXISTS health.pep_courses (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  exposure_id uuid NOT NULL UNIQUE REFERENCES health.exposures(id) ON DELETE CASCADE,
  regimen text NOT NULL CHECK (length(regimen) BETWEEN 2 AND 160),   -- as prescribed, in the facility's own words
  rig_given boolean NOT NULL DEFAULT false,
  prescribed_by uuid NOT NULL REFERENCES auth.users(id),
  prescribed_by_name text,
  prescribed_at timestamptz NOT NULL DEFAULT now(),
  status text NOT NULL DEFAULT 'active' CHECK (status IN ('active', 'completed', 'discontinued', 'lost_to_follow_up')),
  status_note text CHECK (status_note IS NULL OR length(status_note) <= 300),
  updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS health.pep_doses (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  course_id uuid NOT NULL REFERENCES health.pep_courses(id) ON DELETE CASCADE,
  dose_no int NOT NULL CHECK (dose_no BETWEEN 1 AND 10),
  due_on date NOT NULL,                       -- set by the prescribing clinician
  given_on date,
  given_by_name text,
  batch text CHECK (batch IS NULL OR length(batch) <= 40),
  status text NOT NULL DEFAULT 'due' CHECK (status IN ('due', 'given', 'missed', 'cancelled')),
  UNIQUE (course_id, dose_no),
  CHECK ((status = 'given') = (given_on IS NOT NULL))
);
CREATE INDEX IF NOT EXISTS health_doses_due ON health.pep_doses (due_on) WHERE status = 'due';

CREATE TABLE IF NOT EXISTS health.reminder_log (
  id bigserial PRIMARY KEY,
  dose_id uuid NOT NULL REFERENCES health.pep_doses(id) ON DELETE CASCADE,
  at timestamptz NOT NULL DEFAULT now(),
  actor uuid REFERENCES auth.users(id),
  outcome text NOT NULL CHECK (outcome IN ('called_reached', 'called_no_answer', 'message_sent_manually', 'patient_will_attend', 'wrong_number'))
);

CREATE TABLE IF NOT EXISTS health.audit (
  id bigserial PRIMARY KEY,
  at timestamptz NOT NULL DEFAULT now(),
  actor uuid,
  institution_id uuid,
  action text NOT NULL,
  entity text NOT NULL,
  entity_id uuid
);

DO $$ DECLARE t text; BEGIN
  FOREACH t IN ARRAY ARRAY['citizen_notices','exposures','pep_courses','pep_doses','reminder_log','audit'] LOOP
    EXECUTE format('ALTER TABLE health.%I ENABLE ROW LEVEL SECURITY', t);
    EXECUTE format('REVOKE ALL ON health.%I FROM PUBLIC', t);
    BEGIN EXECUTE format('REVOKE ALL ON health.%I FROM anon, authenticated', t); EXCEPTION WHEN undefined_object THEN NULL; END;
  END LOOP;
END $$;
-- The audit trail is append-only, even for the function owner's callers.
CREATE OR REPLACE FUNCTION health.no_rewrite() RETURNS trigger LANGUAGE plpgsql AS $$ BEGIN RAISE EXCEPTION 'The health audit trail cannot be changed'; END $$;
DROP TRIGGER IF EXISTS audit_append_only ON health.audit;
CREATE TRIGGER audit_append_only BEFORE UPDATE OR DELETE ON health.audit FOR EACH ROW EXECUTE FUNCTION health.no_rewrite();

CREATE OR REPLACE FUNCTION health.log(p_institution uuid, p_action text, p_entity text, p_id uuid)
RETURNS void LANGUAGE sql SECURITY DEFINER SET search_path = pg_catalog, public AS $$
  INSERT INTO health.audit (actor, institution_id, action, entity, entity_id) VALUES (auth.uid(), p_institution, p_action, p_entity, p_id)
$$;
REVOKE ALL ON FUNCTION health.log(uuid, text, text, uuid) FROM PUBLIC;

-- ── Shared helpers ─────────────────────────────────────────────────────
CREATE OR REPLACE FUNCTION public.oh_need(p_ok boolean, p_message text DEFAULT 'You do not have access to this')
RETURNS void LANGUAGE plpgsql AS $$ BEGIN IF NOT coalesce(p_ok, false) THEN RAISE EXCEPTION '%', p_message USING ERRCODE = '42501'; END IF; END $$;

CREATE OR REPLACE FUNCTION public.oh_actor_name()
RETURNS text LANGUAGE sql STABLE SECURITY DEFINER SET search_path = pg_catalog, public AS $$
  SELECT coalesce((SELECT display_name FROM public.oh_members WHERE user_id = auth.uid() AND display_name IS NOT NULL LIMIT 1), 'A team member')
$$;

-- Counts below five are never shown outside the facility.
CREATE OR REPLACE FUNCTION public.oh_suppress(n bigint)
RETURNS jsonb LANGUAGE sql IMMUTABLE AS $$ SELECT CASE WHEN n IS NULL THEN 'null'::jsonb WHEN n = 0 THEN '0'::jsonb WHEN n < 5 THEN '"<5"'::jsonb ELSE to_jsonb(n) END $$;

CREATE OR REPLACE FUNCTION public.oh_is_facility(p_institution uuid)
RETURNS boolean LANGUAGE sql STABLE SECURITY DEFINER SET search_path = pg_catalog, public AS $$
  SELECT EXISTS (SELECT 1 FROM public.oh_institutions WHERE id = p_institution AND kind IN ('hospital', 'clinic'))
$$;

-- ── Today: one list for every institution a person belongs to ──────────
CREATE OR REPLACE FUNCTION public.oh_my_today()
RETURNS jsonb LANGUAGE plpgsql STABLE SECURITY DEFINER SET search_path = pg_catalog, public AS $$
DECLARE out jsonb;
BEGIN
  IF auth.uid() IS NULL THEN RETURN '[]'::jsonb; END IF;
  SELECT coalesce(jsonb_agg(r ORDER BY (r->>'order')::int, r->>'name'), '[]'::jsonb) INTO out FROM (
    SELECT jsonb_build_object(
      'institution_id', i.id, 'name', i.name, 'short_name', i.short_name, 'kind', i.kind, 'role', m.role,
      'programme', jsonb_build_object('id', p.id, 'slug', p.slug, 'name', p.name, 'illustrative', p.illustrative),
      'order', CASE i.kind WHEN 'coordinator' THEN 0 WHEN 'municipal' THEN 1 WHEN 'hospital' THEN 2 WHEN 'clinic' THEN 2 WHEN 'laboratory' THEN 3 ELSE 4 END,
      'handoffs_open', (SELECT count(*) FROM public.oh_handoffs h WHERE h.to_institution = i.id AND h.status IN ('open', 'accepted')),
      'handoffs_overdue', (SELECT count(*) FROM public.oh_handoffs h WHERE h.to_institution = i.id AND h.status IN ('open', 'accepted') AND h.due_on < public.oh_today(p.id)),
      'doses_due', CASE WHEN i.kind IN ('hospital', 'clinic') THEN (SELECT count(*) FROM health.pep_doses d JOIN health.pep_courses c ON c.id = d.course_id JOIN health.exposures e ON e.id = c.exposure_id WHERE e.facility_id = i.id AND d.status = 'due' AND d.due_on <= public.oh_today(p.id) AND c.status = 'active') END,
      'notices_new', CASE WHEN i.kind IN ('hospital', 'clinic') THEN (SELECT count(*) FROM health.citizen_notices n WHERE n.facility_id = i.id AND n.status = 'new') END,
      'samples_waiting', CASE WHEN i.kind = 'laboratory' THEN (SELECT count(*) FROM public.oh_samples s WHERE s.laboratory_id = i.id AND s.status IN ('dispatched', 'received', 'testing')) END,
      'services_stale', CASE WHEN i.kind IN ('hospital', 'clinic') THEN (SELECT count(*) FROM (SELECT DISTINCT ON (service) valid_until FROM public.oh_service_status s WHERE s.institution_id = i.id ORDER BY service, verified_at DESC) x WHERE x.valid_until < now()) END
    ) AS r
    FROM public.oh_my_memberships() m JOIN public.oh_institutions i ON i.id = m.institution_id JOIN public.oh_programmes p ON p.id = i.programme_id
  ) s;
  RETURN out;
END $$;

-- ── Clinic: register a presentation (records staff, nurses, clinicians) ──
CREATE OR REPLACE FUNCTION public.oh_record_exposure(
  p_facility uuid, p_exposure_on date, p_kind text, p_ward text, p_age_band text DEFAULT 'not_recorded', p_sex text DEFAULT 'not_recorded',
  p_patient_ref text DEFAULT NULL, p_species text DEFAULT 'dog', p_ownership text DEFAULT 'unknown', p_animal_description text DEFAULT NULL,
  p_animal_place text DEFAULT NULL, p_category text DEFAULT 'not_recorded', p_source text DEFAULT 'walk_in', p_notice uuid DEFAULT NULL,
  p_contact_phone text DEFAULT NULL, p_reminder_consent boolean DEFAULT false, p_request_followup boolean DEFAULT true)
RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path = pg_catalog, public AS $$
DECLARE r text := public.oh_role_in(p_facility); prog uuid; eid uuid; c text; hid uuid; ngo uuid; wardv text := nullif(btrim(p_ward), '');
BEGIN
  PERFORM public.oh_need(public.oh_is_facility(p_facility) AND r IN ('clinician', 'nurse', 'records', 'lead'), 'Only staff of this facility can record a bite');
  PERFORM public.oh_need(p_category = 'not_recorded' OR r = 'clinician', 'Only a clinician can record the exposure category');
  SELECT programme_id INTO prog FROM public.oh_institutions WHERE id = p_facility;
  PERFORM public.oh_need(p_exposure_on <= public.oh_today(prog), 'The date it happened cannot be in the future');
  PERFORM public.oh_need(p_exposure_on >= public.oh_today(prog) - 365, 'The date it happened is more than a year ago');
  c := 'BX-' || to_char(public.oh_today(prog), 'YYMM') || '-' || upper(substr(replace(gen_random_uuid()::text, '-', ''), 1, 5));
  INSERT INTO health.exposures (programme_id, facility_id, code, patient_ref, age_band, sex, ward, exposure_on, presented_on, exposure_kind, category, category_by, category_by_name,
    animal_species, animal_ownership, animal_description, animal_place, source, notice_id, contact_phone, reminder_consent, created_by)
  VALUES (prog, p_facility, c, nullif(btrim(p_patient_ref), ''), p_age_band, p_sex, wardv, p_exposure_on, public.oh_today(prog), p_kind, p_category,
    CASE WHEN p_category <> 'not_recorded' THEN auth.uid() END, CASE WHEN p_category <> 'not_recorded' THEN public.oh_actor_name() END,
    p_species, p_ownership, nullif(btrim(p_animal_description), ''), nullif(btrim(p_animal_place), ''), p_source, p_notice,
    CASE WHEN p_reminder_consent THEN nullif(btrim(p_contact_phone), '') END, p_reminder_consent AND nullif(btrim(p_contact_phone), '') IS NOT NULL, auth.uid())
  RETURNING id INTO eid;
  IF p_notice IS NOT NULL THEN UPDATE health.citizen_notices SET status = 'presented' WHERE id = p_notice AND programme_id = prog; END IF;
  -- One Health link: the animal side gets a follow-up with place and description only.
  IF p_request_followup AND p_ownership <> 'owned' AND wardv IS NOT NULL THEN
    SELECT institution_id INTO ngo FROM public.oh_ward_assignments WHERE programme_id = prog AND ward = wardv AND duty = 'animal_followup';
    IF ngo IS NOT NULL THEN
      INSERT INTO public.oh_handoffs (programme_id, kind, from_institution, to_institution, title, detail, ward, place, status, due_on, created_by)
      VALUES (prog, 'animal_followup', p_facility, ngo,
        'Find and observe the ' || CASE p_species WHEN 'unknown' THEN 'animal' ELSE p_species END || ' involved in ' || CASE p_kind WHEN 'bite' THEN 'a bite' WHEN 'scratch' THEN 'a scratch' WHEN 'lick_broken_skin' THEN 'a lick on broken skin' ELSE 'contact' END || ' on ' || to_char(p_exposure_on, 'DD Mon'),
        concat_ws(E'\n', CASE WHEN p_animal_description IS NOT NULL THEN 'Animal: ' || p_animal_description END,
          'The facility asked for the animal to be located and its health recorded. Record what you find; if it is sick or dies, arrange a sample for the laboratory.',
          'No patient details are shared with this request.'),
        wardv, nullif(btrim(p_animal_place), ''), 'open', p_exposure_on + 3, auth.uid())
      RETURNING id INTO hid;
      UPDATE health.exposures SET handoff_id = hid WHERE id = eid;
    END IF;
  END IF;
  PERFORM health.log(p_facility, 'record_exposure', 'exposure', eid);
  RETURN jsonb_build_object('id', eid, 'code', c, 'handoff_id', hid);
END $$;

-- Clinician records the category later, if it was not known at registration.
CREATE OR REPLACE FUNCTION public.oh_set_category(p_exposure uuid, p_category text)
RETURNS void LANGUAGE plpgsql SECURITY DEFINER SET search_path = pg_catalog, public AS $$
DECLARE f uuid;
BEGIN
  SELECT facility_id INTO f FROM health.exposures WHERE id = p_exposure;
  PERFORM public.oh_need(f IS NOT NULL AND public.oh_role_in(f) = 'clinician', 'Only a clinician of this facility can record the category');
  PERFORM public.oh_need(p_category IN ('I', 'II', 'III'), 'Choose category I, II or III');
  UPDATE health.exposures SET category = p_category, category_by = auth.uid(), category_by_name = public.oh_actor_name(), updated_at = now() WHERE id = p_exposure;
  PERFORM health.log(f, 'set_category', 'exposure', p_exposure);
END $$;

-- Clinician prescribes: the regimen as written and the date for each dose.
CREATE OR REPLACE FUNCTION public.oh_prescribe(p_exposure uuid, p_regimen text, p_rig_given boolean, p_due_dates date[])
RETURNS uuid LANGUAGE plpgsql SECURITY DEFINER SET search_path = pg_catalog, public AS $$
DECLARE f uuid; cid uuid; i int; exp_on date;
BEGIN
  SELECT facility_id, exposure_on INTO f, exp_on FROM health.exposures WHERE id = p_exposure;
  PERFORM public.oh_need(f IS NOT NULL AND public.oh_role_in(f) = 'clinician', 'Only a clinician of this facility can prescribe');
  PERFORM public.oh_need(coalesce(array_length(p_due_dates, 1), 0) BETWEEN 1 AND 10, 'Give the date of each dose the clinician prescribed');
  PERFORM public.oh_need(length(btrim(coalesce(p_regimen, ''))) >= 2, 'Write the regimen as prescribed');
  FOR i IN 1 .. array_length(p_due_dates, 1) LOOP
    PERFORM public.oh_need(p_due_dates[i] >= exp_on AND (i = 1 OR p_due_dates[i] >= p_due_dates[i - 1]), 'Dose dates must be on or after the exposure and in order');
  END LOOP;
  INSERT INTO health.pep_courses (exposure_id, regimen, rig_given, prescribed_by, prescribed_by_name)
  VALUES (p_exposure, btrim(p_regimen), coalesce(p_rig_given, false), auth.uid(), public.oh_actor_name()) RETURNING id INTO cid;
  FOR i IN 1 .. array_length(p_due_dates, 1) LOOP
    INSERT INTO health.pep_doses (course_id, dose_no, due_on) VALUES (cid, i, p_due_dates[i]);
  END LOOP;
  PERFORM health.log(f, 'prescribe', 'pep_course', cid);
  RETURN cid;
END $$;

-- Nurse or clinician records a dose given (or missed).
CREATE OR REPLACE FUNCTION public.oh_record_dose(p_dose uuid, p_status text, p_given_on date DEFAULT NULL, p_batch text DEFAULT NULL)
RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path = pg_catalog, public AS $$
DECLARE f uuid; cid uuid; remaining int; prog uuid;
BEGIN
  SELECT e.facility_id, c.id, e.programme_id INTO f, cid, prog FROM health.pep_doses d JOIN health.pep_courses c ON c.id = d.course_id JOIN health.exposures e ON e.id = c.exposure_id WHERE d.id = p_dose;
  PERFORM public.oh_need(f IS NOT NULL AND public.oh_role_in(f) IN ('clinician', 'nurse'), 'Only a nurse or clinician of this facility can record a dose');
  PERFORM public.oh_need(p_status IN ('given', 'missed'), 'Record the dose as given or missed');
  p_given_on := coalesce(p_given_on, public.oh_today(prog));
  PERFORM public.oh_need(p_status <> 'given' OR p_given_on <= public.oh_today(prog), 'A dose cannot be given in the future');
  UPDATE health.pep_doses SET status = p_status, given_on = CASE WHEN p_status = 'given' THEN p_given_on END,
    given_by_name = CASE WHEN p_status = 'given' THEN public.oh_actor_name() END, batch = CASE WHEN p_status = 'given' THEN nullif(btrim(p_batch), '') END
   WHERE id = p_dose;
  SELECT count(*) INTO remaining FROM health.pep_doses WHERE course_id = cid AND status = 'due';
  IF remaining = 0 AND NOT EXISTS (SELECT 1 FROM health.pep_doses WHERE course_id = cid AND status = 'missed') THEN
    UPDATE health.pep_courses SET status = 'completed', updated_at = now() WHERE id = cid AND status = 'active';
  END IF;
  PERFORM health.log(f, 'record_dose_' || p_status, 'pep_dose', p_dose);
  RETURN jsonb_build_object('remaining', remaining);
END $$;

CREATE OR REPLACE FUNCTION public.oh_set_course_status(p_course uuid, p_status text, p_note text DEFAULT NULL)
RETURNS void LANGUAGE plpgsql SECURITY DEFINER SET search_path = pg_catalog, public AS $$
DECLARE f uuid;
BEGIN
  SELECT e.facility_id INTO f FROM health.pep_courses c JOIN health.exposures e ON e.id = c.exposure_id WHERE c.id = p_course;
  PERFORM public.oh_need(f IS NOT NULL AND public.oh_role_in(f) = 'clinician', 'Only a clinician can change the course');
  PERFORM public.oh_need(p_status IN ('active', 'completed', 'discontinued', 'lost_to_follow_up'), 'Unknown course status');
  UPDATE health.pep_courses SET status = p_status, status_note = nullif(btrim(p_note), ''), updated_at = now() WHERE id = p_course;
  IF p_status IN ('discontinued', 'lost_to_follow_up') THEN UPDATE health.pep_doses SET status = 'cancelled' WHERE course_id = p_course AND status = 'due'; END IF;
  PERFORM health.log(f, 'course_' || p_status, 'pep_course', p_course);
END $$;

