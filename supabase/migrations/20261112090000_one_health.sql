-- The facility's own register (facility staff only).
CREATE OR REPLACE FUNCTION public.oh_clinic_register(p_facility uuid, p_filter text DEFAULT 'all', p_limit int DEFAULT 50)
RETURNS jsonb LANGUAGE plpgsql STABLE SECURITY DEFINER SET search_path = pg_catalog, public AS $$
DECLARE out jsonb;
BEGIN
  PERFORM public.oh_need(public.oh_is_facility(p_facility) AND public.oh_role_in(p_facility) IS NOT NULL, 'Only staff of this facility can read its register');
  SELECT coalesce(jsonb_agg(x ORDER BY x->>'presented_on' DESC, x->>'code' DESC), '[]'::jsonb) INTO out FROM (
    SELECT jsonb_build_object('id', e.id, 'code', e.code, 'patient_ref', e.patient_ref, 'age_band', e.age_band, 'sex', e.sex, 'ward', e.ward,
      'exposure_on', e.exposure_on, 'presented_on', e.presented_on, 'kind', e.exposure_kind, 'category', e.category, 'species', e.animal_species,
      'course_status', c.status, 'regimen', c.regimen,
      'doses_given', (SELECT count(*) FROM health.pep_doses d WHERE d.course_id = c.id AND d.status = 'given'),
      'doses_total', (SELECT count(*) FROM health.pep_doses d WHERE d.course_id = c.id AND d.status <> 'cancelled'),
      'next_due', (SELECT min(due_on) FROM health.pep_doses d WHERE d.course_id = c.id AND d.status = 'due'),
      'handoff_status', (SELECT status FROM public.oh_handoffs h WHERE h.id = e.handoff_id)) AS x
    FROM health.exposures e LEFT JOIN health.pep_courses c ON c.exposure_id = e.id
    WHERE e.facility_id = p_facility
      AND (p_filter = 'all'
        OR (p_filter = 'needs_assessment' AND (e.category = 'not_recorded' OR (c.id IS NULL AND e.category IN ('II', 'III'))))
        OR (p_filter = 'active' AND c.status = 'active')
        OR (p_filter = 'closed' AND c.status IN ('completed', 'discontinued', 'lost_to_follow_up')))
    ORDER BY e.presented_on DESC LIMIT least(greatest(p_limit, 1), 200)
  ) s;
  RETURN out;
END $$;

-- Doses due today or overdue, with the phone only where the patient consented.
CREATE OR REPLACE FUNCTION public.oh_clinic_due(p_facility uuid)
RETURNS jsonb LANGUAGE plpgsql STABLE SECURITY DEFINER SET search_path = pg_catalog, public AS $$
DECLARE out jsonb;
BEGIN
  PERFORM public.oh_need(public.oh_is_facility(p_facility) AND public.oh_role_in(p_facility) IS NOT NULL, 'Only staff of this facility can read its schedule');
  SELECT coalesce(jsonb_agg(x ORDER BY x->>'due_on', x->>'code'), '[]'::jsonb) INTO out FROM (
    SELECT jsonb_build_object('dose_id', d.id, 'dose_no', d.dose_no, 'doses_total', (SELECT count(*) FROM health.pep_doses z WHERE z.course_id = c.id AND z.status <> 'cancelled'),
      'due_on', d.due_on, 'exposure_id', e.id, 'code', e.code, 'patient_ref', e.patient_ref, 'age_band', e.age_band, 'regimen', c.regimen,
      'phone', CASE WHEN e.reminder_consent THEN e.contact_phone END,
      'last_reminder', (SELECT jsonb_build_object('at', r.at, 'outcome', r.outcome) FROM health.reminder_log r WHERE r.dose_id = d.id ORDER BY r.at DESC LIMIT 1)) AS x
    FROM health.pep_doses d JOIN health.pep_courses c ON c.id = d.course_id JOIN health.exposures e ON e.id = c.exposure_id
    WHERE e.facility_id = p_facility AND c.status = 'active' AND d.status = 'due' AND d.due_on <= public.oh_today(e.programme_id) + 1
  ) s;
  RETURN out;
END $$;

CREATE OR REPLACE FUNCTION public.oh_clinic_exposure(p_exposure uuid)
RETURNS jsonb LANGUAGE plpgsql STABLE SECURITY DEFINER SET search_path = pg_catalog, public AS $$
DECLARE e health.exposures; c health.pep_courses; out jsonb;
BEGIN
  SELECT * INTO e FROM health.exposures WHERE id = p_exposure;
  PERFORM public.oh_need(e.id IS NOT NULL AND public.oh_role_in(e.facility_id) IS NOT NULL, 'Only staff of this facility can open this record');
  SELECT * INTO c FROM health.pep_courses WHERE exposure_id = e.id;
  PERFORM health.log(e.facility_id, 'read', 'exposure', e.id);
  out := to_jsonb(e) - 'created_by' - 'category_by' || jsonb_build_object(
    'my_role', public.oh_role_in(e.facility_id),
    'course', CASE WHEN c.id IS NULL THEN NULL ELSE to_jsonb(c) - 'prescribed_by' END,
    'doses', coalesce((SELECT jsonb_agg(to_jsonb(d) ORDER BY d.dose_no) FROM health.pep_doses d WHERE d.course_id = c.id), '[]'::jsonb),
    'handoff', (SELECT jsonb_build_object('id', h.id, 'status', h.status, 'to', i.name, 'outcome', h.outcome) FROM public.oh_handoffs h JOIN public.oh_institutions i ON i.id = h.to_institution WHERE h.id = e.handoff_id),
    'history', coalesce((SELECT jsonb_agg(jsonb_build_object('at', a.at, 'action', a.action) ORDER BY a.at) FROM health.audit a WHERE a.entity_id IN (e.id, c.id) OR a.entity_id IN (SELECT id FROM health.pep_doses WHERE course_id = c.id)), '[]'::jsonb));
  RETURN out;
END $$;

-- Citizen bite notice (public). Goes to the programme's first listed facility in the ward, else the first listed facility.
CREATE OR REPLACE FUNCTION public.oh_submit_bite_notice(p_programme_slug text, p_happened_on date, p_ward text, p_place text, p_species text, p_animal_description text, p_phone text, p_consent boolean)
RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path = pg_catalog, public AS $$
DECLARE prog uuid; fac uuid; nid uuid;
BEGIN
  SELECT id INTO prog FROM public.oh_programmes WHERE slug = p_programme_slug AND status IN ('pilot', 'active');
  PERFORM public.oh_need(prog IS NOT NULL, 'This programme is not accepting notices');
  PERFORM public.oh_need(p_happened_on BETWEEN public.oh_today(prog) - 30 AND public.oh_today(prog), 'Give a date in the last 30 days');
  SELECT id INTO fac FROM public.oh_institutions WHERE programme_id = prog AND kind IN ('hospital', 'clinic') AND listed_publicly
   ORDER BY (ward = nullif(btrim(p_ward), '')) DESC NULLS LAST, kind = 'hospital' DESC, name LIMIT 1;
  INSERT INTO health.citizen_notices (programme_id, facility_id, happened_on, ward, place, animal_species, animal_description, callback_phone, callback_consent)
  VALUES (prog, fac, p_happened_on, nullif(btrim(p_ward), ''), left(nullif(btrim(p_place), ''), 200), coalesce(nullif(p_species, ''), 'unknown'), left(nullif(btrim(p_animal_description), ''), 300),
    CASE WHEN p_consent THEN nullif(regexp_replace(coalesce(p_phone, ''), '[^0-9+ ]', '', 'g'), '') END, coalesce(p_consent, false))
  RETURNING id INTO nid;
  INSERT INTO health.audit (actor, institution_id, action, entity, entity_id) VALUES (auth.uid(), fac, 'citizen_notice', 'citizen_notice', nid);
  RETURN jsonb_build_object('received', true, 'facility', (SELECT jsonb_build_object('name', name, 'address', address, 'phone', phone, 'hours', hours) FROM public.oh_institutions WHERE id = fac));
END $$;

