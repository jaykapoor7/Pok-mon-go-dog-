-- Public finder: listed facilities and the latest confirmation of each service; stale means not verified.
CREATE OR REPLACE FUNCTION public.oh_public_services(p_programme_slug text)
RETURNS jsonb LANGUAGE sql STABLE SECURITY DEFINER SET search_path = pg_catalog, public AS $$
  SELECT jsonb_build_object('programme', (SELECT jsonb_build_object('name', name, 'city', city, 'illustrative', illustrative, 'wards', wards) FROM public.oh_programmes WHERE slug = p_programme_slug),
    'facilities', coalesce(jsonb_agg(f ORDER BY f->>'name'), '[]'::jsonb)) FROM (
    SELECT jsonb_build_object('id', i.id, 'name', i.name, 'kind', i.kind, 'ward', i.ward, 'address', i.address, 'phone', i.phone, 'hours', i.hours, 'lat', i.lat, 'lng', i.lng,
      'services', coalesce((SELECT jsonb_agg(jsonb_build_object('service', s.service,
          'status', CASE WHEN s.valid_until >= now() THEN s.status ELSE 'not_verified' END,
          'verified_at', s.verified_at, 'valid_until', s.valid_until)) FROM (
          SELECT DISTINCT ON (service) * FROM public.oh_service_status WHERE institution_id = i.id ORDER BY service, verified_at DESC) s), '[]'::jsonb)) AS f
    FROM public.oh_institutions i JOIN public.oh_programmes p ON p.id = i.programme_id
    WHERE p.slug = p_programme_slug AND i.listed_publicly AND i.kind IN ('hospital', 'clinic')
  ) x
$$;

-- ── Handoffs ───────────────────────────────────────────────────────────
CREATE OR REPLACE FUNCTION public.oh_handoff_act(p_handoff uuid, p_action text, p_outcome text DEFAULT NULL, p_animal uuid DEFAULT NULL)
RETURNS void LANGUAGE plpgsql SECURITY DEFINER SET search_path = pg_catalog, public AS $$
DECLARE h public.oh_handoffs;
BEGIN
  SELECT * INTO h FROM public.oh_handoffs WHERE id = p_handoff;
  PERFORM public.oh_need(h.id IS NOT NULL AND public.oh_role_in(h.to_institution) IS NOT NULL, 'Only the receiving team can act on this');
  PERFORM public.oh_need(p_action IN ('accept', 'done', 'decline'), 'Accept, complete or decline');
  PERFORM public.oh_need(p_action = 'accept' OR length(btrim(coalesce(p_outcome, ''))) >= 3, 'Say what was found or why it was declined');
  PERFORM public.oh_need(h.status NOT IN ('done', 'declined'), 'This has already been closed');
  PERFORM public.oh_need(p_animal IS NULL OR EXISTS (SELECT 1 FROM public.dogs d JOIN public.oh_institutions i ON i.ngo_id = d.ngo_id WHERE d.id = p_animal AND i.id = h.to_institution), 'That animal is not on your register');
  UPDATE public.oh_handoffs SET status = CASE p_action WHEN 'accept' THEN 'accepted' WHEN 'done' THEN 'done' ELSE 'declined' END,
    outcome = coalesce(nullif(btrim(p_outcome), ''), outcome), animal_id = coalesce(p_animal, animal_id), updated_at = now(),
    closed_at = CASE WHEN p_action <> 'accept' THEN now() END, closed_by_name = CASE WHEN p_action <> 'accept' THEN public.oh_actor_name() END
  WHERE id = p_handoff;
END $$;

-- Coordinators can raise a handoff to any institution in the programme (e.g. a vaccination request).
CREATE OR REPLACE FUNCTION public.oh_raise_handoff(p_programme uuid, p_kind text, p_to uuid, p_title text, p_detail text, p_ward text, p_due date)
RETURNS uuid LANGUAGE plpgsql SECURITY DEFINER SET search_path = pg_catalog, public AS $$
DECLARE hid uuid; me uuid;
BEGIN
  PERFORM public.oh_need(public.oh_can_oversee(p_programme), 'Only programme coordinators can raise this');
  PERFORM public.oh_need(EXISTS (SELECT 1 FROM public.oh_institutions WHERE id = p_to AND programme_id = p_programme), 'Choose a programme partner');
  SELECT institution_id INTO me FROM public.oh_my_memberships() WHERE programme_id = p_programme AND kind IN ('coordinator', 'municipal') LIMIT 1;
  INSERT INTO public.oh_handoffs (programme_id, kind, from_institution, to_institution, title, detail, ward, due_on, created_by)
  VALUES (p_programme, p_kind, me, p_to, btrim(p_title), nullif(btrim(p_detail), ''), nullif(btrim(p_ward), ''), p_due, auth.uid()) RETURNING id INTO hid;
  RETURN hid;
END $$;

-- ── Samples ────────────────────────────────────────────────────────────
CREATE OR REPLACE FUNCTION public.oh_submit_sample(p_from uuid, p_lab uuid, p_species text, p_type text, p_collected_on date, p_ward text, p_place text, p_reason text, p_animal uuid DEFAULT NULL, p_handoff uuid DEFAULT NULL)
RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path = pg_catalog, public AS $$
DECLARE prog uuid; sid uuid; c text;
BEGIN
  PERFORM public.oh_need(public.oh_role_in(p_from) IS NOT NULL, 'Only members of the submitting team can send a sample');
  SELECT programme_id INTO prog FROM public.oh_institutions WHERE id = p_from;
  PERFORM public.oh_need(EXISTS (SELECT 1 FROM public.oh_institutions WHERE id = p_lab AND kind = 'laboratory' AND programme_id = prog), 'Choose a programme laboratory');
  PERFORM public.oh_need(p_collected_on <= public.oh_today(prog), 'Collection date cannot be in the future');
  c := 'S-' || to_char(public.oh_today(prog), 'YYMM') || '-' || upper(substr(replace(gen_random_uuid()::text, '-', ''), 1, 5));
  INSERT INTO public.oh_samples (programme_id, code, submitted_by, laboratory_id, animal_id, species, sample_type, reason, collected_on, collected_by_name, ward, place, status)
  VALUES (prog, c, p_from, p_lab, p_animal, p_species, p_type, nullif(btrim(p_reason), ''), p_collected_on, public.oh_actor_name(), nullif(btrim(p_ward), ''), nullif(btrim(p_place), ''), 'dispatched')
  RETURNING id INTO sid;
  INSERT INTO public.oh_sample_events (sample_id, actor, actor_name, institution_id, action, note) VALUES
    (sid, auth.uid(), public.oh_actor_name(), p_from, 'collected', NULL), (sid, auth.uid(), public.oh_actor_name(), p_from, 'dispatched', NULL);
  IF p_handoff IS NOT NULL THEN UPDATE public.oh_handoffs SET sample_id = sid, updated_at = now() WHERE id = p_handoff AND public.oh_role_in(to_institution) IS NOT NULL; END IF;
  RETURN jsonb_build_object('id', sid, 'code', c);
END $$;

CREATE OR REPLACE FUNCTION public.oh_sample_step(p_sample uuid, p_action text, p_note text DEFAULT NULL, p_result text DEFAULT NULL, p_method text DEFAULT NULL)
RETURNS void LANGUAGE plpgsql SECURITY DEFINER SET search_path = pg_catalog, public AS $$
DECLARE s public.oh_samples; nxt text; coord uuid;
BEGIN
  SELECT * INTO s FROM public.oh_samples WHERE id = p_sample;
  PERFORM public.oh_need(s.id IS NOT NULL AND public.oh_role_in(s.laboratory_id) IN ('lab_scientist', 'lead'), 'Only the receiving laboratory can update this sample');
  nxt := CASE
    WHEN p_action = 'received' AND s.status IN ('collected', 'dispatched') THEN 'received'
    WHEN p_action = 'testing' AND s.status = 'received' THEN 'testing'
    WHEN p_action = 'resulted' AND s.status = 'testing' THEN 'resulted'
    WHEN p_action = 'rejected' AND s.status IN ('dispatched', 'received') THEN 'rejected'
    WHEN p_action = 'note' THEN s.status END;
  PERFORM public.oh_need(nxt IS NOT NULL, 'That step is not possible from ' || s.status);
  PERFORM public.oh_need(p_action <> 'resulted' OR (p_result IN ('positive', 'negative', 'inconclusive') AND length(btrim(coalesce(p_method, ''))) >= 2), 'Record the result and the test method');
  PERFORM public.oh_need(p_action <> 'rejected' OR length(btrim(coalesce(p_note, ''))) >= 3, 'Say why the sample was rejected');
  UPDATE public.oh_samples SET status = nxt,
    result = CASE WHEN p_action = 'resulted' THEN p_result ELSE result END, method = CASE WHEN p_action = 'resulted' THEN btrim(p_method) ELSE method END,
    result_note = CASE WHEN p_action IN ('resulted', 'rejected') THEN nullif(btrim(p_note), '') ELSE result_note END,
    resulted_at = CASE WHEN p_action = 'resulted' THEN now() ELSE resulted_at END, resulted_by_name = CASE WHEN p_action = 'resulted' THEN public.oh_actor_name() ELSE resulted_by_name END
  WHERE id = p_sample;
  INSERT INTO public.oh_sample_events (sample_id, actor, actor_name, institution_id, action, note) VALUES (p_sample, auth.uid(), public.oh_actor_name(), s.laboratory_id, p_action, nullif(btrim(p_note), ''));
  IF p_action = 'resulted' THEN
    INSERT INTO public.oh_handoffs (programme_id, kind, from_institution, to_institution, title, detail, ward, place, animal_id, sample_id, created_by)
    VALUES (s.programme_id, 'result_notice', s.laboratory_id, s.submitted_by, 'Result for sample ' || s.code || ': ' || p_result,
      'Method: ' || btrim(p_method) || CASE WHEN p_result = 'positive' THEN E'\nA positive result has been shared with the programme coordinators.' ELSE '' END, s.ward, s.place, s.animal_id, s.id, auth.uid());
    IF p_result = 'positive' THEN
      FOR coord IN SELECT id FROM public.oh_institutions WHERE programme_id = s.programme_id AND kind IN ('coordinator', 'municipal') LOOP
        INSERT INTO public.oh_handoffs (programme_id, kind, from_institution, to_institution, title, detail, ward, place, sample_id, created_by)
        VALUES (s.programme_id, 'result_notice', s.laboratory_id, coord, 'Laboratory-confirmed rabies: ' || coalesce(s.ward, 'ward not recorded'),
          'Sample ' || s.code || ' (' || s.species || ') tested positive by ' || btrim(p_method) || '. Decide the response with the partners.', s.ward, s.place, s.id, auth.uid());
      END LOOP;
    END IF;
  END IF;
END $$;

-- ── Programme overview (aggregates only, small counts suppressed) ──────
CREATE OR REPLACE FUNCTION public.oh_programme_overview(p_programme uuid, p_days int DEFAULT 90)
RETURNS jsonb LANGUAGE plpgsql STABLE SECURITY DEFINER SET search_path = pg_catalog, public AS $$
DECLARE since date := public.oh_today(p_programme) - least(greatest(p_days, 7), 730); p public.oh_programmes; out jsonb; td date := public.oh_today(p_programme);
BEGIN
  PERFORM public.oh_need(public.oh_in_programme(p_programme), 'Only programme partners can see the overview');
  SELECT * INTO p FROM public.oh_programmes WHERE id = p_programme;
  out := jsonb_build_object(
    'programme', jsonb_build_object('id', p.id, 'slug', p.slug, 'name', p.name, 'city', p.city, 'status', p.status, 'illustrative', p.illustrative, 'target', p.vaccination_target, 'summary', p.summary),
    'since', since,
    'can_oversee', public.oh_can_oversee(p_programme),
    'partners', (SELECT coalesce(jsonb_agg(jsonb_build_object('id', i.id, 'name', i.name, 'short_name', i.short_name, 'kind', i.kind, 'responsibilities', i.responsibilities,
        'open', (SELECT count(*) FROM public.oh_handoffs h WHERE h.to_institution = i.id AND h.status IN ('open', 'accepted')),
        'overdue', (SELECT count(*) FROM public.oh_handoffs h WHERE h.to_institution = i.id AND h.status IN ('open', 'accepted') AND h.due_on < td)) ORDER BY i.kind, i.name), '[]') FROM public.oh_institutions i WHERE i.programme_id = p_programme),
    'exposures', jsonb_build_object(
      'total', public.oh_suppress((SELECT count(*) FROM health.exposures WHERE programme_id = p_programme AND exposure_on >= since)),
      'category_iii', public.oh_suppress((SELECT count(*) FROM health.exposures WHERE programme_id = p_programme AND exposure_on >= since AND category = 'III')),
      'by_week', (SELECT coalesce(jsonb_agg(jsonb_build_object('week', w, 'n', public.oh_suppress(n)) ORDER BY w), '[]') FROM (
         SELECT date_trunc('week', exposure_on)::date w, count(*) n FROM health.exposures WHERE programme_id = p_programme AND exposure_on >= since GROUP BY 1) x),
      'by_ward', (SELECT coalesce(jsonb_agg(jsonb_build_object('ward', ward, 'n', public.oh_suppress(n)) ORDER BY n DESC), '[]') FROM (
         SELECT coalesce(ward, 'Not recorded') ward, count(*) n FROM health.exposures WHERE programme_id = p_programme AND exposure_on >= since GROUP BY 1) x)),
    'pep', (SELECT jsonb_build_object('courses', public.oh_suppress(count(*)),
        'completed', public.oh_suppress(count(*) FILTER (WHERE c.status = 'completed')),
        'lost', public.oh_suppress(count(*) FILTER (WHERE c.status = 'lost_to_follow_up')),
        'completion_rate', CASE WHEN count(*) FILTER (WHERE c.status <> 'active') >= 5 THEN round(count(*) FILTER (WHERE c.status = 'completed')::numeric / count(*) FILTER (WHERE c.status <> 'active'), 2) END)
      FROM health.pep_courses c JOIN health.exposures e ON e.id = c.exposure_id WHERE e.programme_id = p_programme AND e.exposure_on >= since),
    'samples', (SELECT jsonb_build_object('total', count(*), 'waiting', count(*) FILTER (WHERE status IN ('dispatched', 'received', 'testing')),
        'positive', count(*) FILTER (WHERE result = 'positive'), 'negative', count(*) FILTER (WHERE result = 'negative'),
        'median_days_to_result', percentile_cont(0.5) WITHIN GROUP (ORDER BY extract(epoch FROM resulted_at - created_at) / 86400) FILTER (WHERE resulted_at IS NOT NULL),
        'positive_wards', (SELECT coalesce(jsonb_agg(DISTINCT coalesce(ward, 'Not recorded')), '[]') FROM public.oh_samples z WHERE z.programme_id = p_programme AND z.result = 'positive' AND z.collected_on >= since))
      FROM public.oh_samples WHERE programme_id = p_programme AND collected_on >= since),
    'handoffs', (SELECT jsonb_build_object('open', count(*) FILTER (WHERE status IN ('open', 'accepted')), 'overdue', count(*) FILTER (WHERE status IN ('open', 'accepted') AND due_on < td),
        'done', count(*) FILTER (WHERE status = 'done'),
        'median_days_to_close', percentile_cont(0.5) WITHIN GROUP (ORDER BY extract(epoch FROM closed_at - created_at) / 86400) FILTER (WHERE closed_at IS NOT NULL))
      FROM public.oh_handoffs WHERE programme_id = p_programme AND created_at >= since),
    'services', (SELECT jsonb_build_object('facilities', count(DISTINCT i.id), 'confirmed', count(*) FILTER (WHERE s.valid_until >= now()), 'stale', count(*) FILTER (WHERE s.valid_until < now()),
        'arv_unavailable', count(*) FILTER (WHERE s.service = 'arv' AND s.status = 'unavailable' AND s.valid_until >= now()))
      FROM public.oh_institutions i LEFT JOIN LATERAL (SELECT DISTINCT ON (service) * FROM public.oh_service_status x WHERE x.institution_id = i.id ORDER BY service, verified_at DESC) s ON true
      WHERE i.programme_id = p_programme AND i.kind IN ('hospital', 'clinic')),
    'vaccination', (SELECT coalesce(jsonb_agg(v ORDER BY v->>'ward'), '[]') FROM (
      SELECT jsonb_build_object('ward', w.ward,
        'registered', (SELECT count(*) FROM public.dogs d JOIN public.oh_institutions i ON i.ngo_id = d.ngo_id AND i.programme_id = p_programme WHERE d.zone = w.ward),
        'vaccinated', (SELECT count(*) FROM public.dogs d JOIN public.oh_institutions i ON i.ngo_id = d.ngo_id AND i.programme_id = p_programme WHERE d.zone = w.ward AND d.vaccination_status = 'vaccinated'),
        'estimate', (SELECT jsonb_build_object('dogs', e.dogs_estimated, 'method', e.method, 'source', e.source, 'on', e.estimated_on) FROM public.oh_ward_estimates e WHERE e.programme_id = p_programme AND e.ward = w.ward ORDER BY e.estimated_on DESC LIMIT 1)) v
      FROM unnest(p.wards) AS w(ward)) x),
    'training', (SELECT jsonb_build_object('sessions', count(*), 'participants', coalesce(sum(participants), 0),
        'by_audience', (SELECT coalesce(jsonb_object_agg(audience, n), '{}') FROM (SELECT audience, sum(participants) n FROM public.oh_trainings WHERE programme_id = p_programme GROUP BY 1) a))
      FROM public.oh_trainings WHERE programme_id = p_programme)
  );
  RETURN out;
END $$;

CREATE OR REPLACE FUNCTION public.oh_record_training(p_programme uuid, p_title text, p_audience text, p_held_on date, p_participants int, p_institutions int DEFAULT NULL, p_notes text DEFAULT NULL)
RETURNS uuid LANGUAGE plpgsql SECURITY DEFINER SET search_path = pg_catalog, public AS $$
DECLARE tid uuid; prov uuid;
BEGIN
  SELECT institution_id INTO prov FROM public.oh_my_memberships() WHERE programme_id = p_programme AND (kind IN ('coordinator', 'municipal', 'laboratory', 'training') OR role IN ('lead', 'trainer')) LIMIT 1;
  PERFORM public.oh_need(prov IS NOT NULL, 'Only programme coordinators, laboratories or trainers can record training');
  INSERT INTO public.oh_trainings (programme_id, provider_id, title, audience, held_on, participants, institutions_reached, notes, recorded_by)
  VALUES (p_programme, prov, btrim(p_title), p_audience, p_held_on, p_participants, p_institutions, nullif(btrim(p_notes), ''), auth.uid()) RETURNING id INTO tid;
  RETURN tid;
END $$;

CREATE OR REPLACE FUNCTION public.oh_record_estimate(p_programme uuid, p_ward text, p_dogs int, p_method text, p_source text, p_on date)
RETURNS uuid LANGUAGE plpgsql SECURITY DEFINER SET search_path = pg_catalog, public AS $$
DECLARE eid uuid;
BEGIN
  PERFORM public.oh_need(public.oh_can_oversee(p_programme), 'Only programme coordinators can record a population estimate');
  INSERT INTO public.oh_ward_estimates (programme_id, ward, dogs_estimated, method, source, estimated_on, recorded_by)
  VALUES (p_programme, btrim(p_ward), p_dogs, btrim(p_method), btrim(p_source), p_on, auth.uid()) RETURNING id INTO eid;
  RETURN eid;
END $$;

-- ── Function grants: authenticated only, except the two public entry points ──
DO $$ DECLARE f record; BEGIN
  FOR f IN SELECT p.oid::regprocedure AS sig, p.proname FROM pg_proc p JOIN pg_namespace n ON n.oid = p.pronamespace WHERE n.nspname = 'public' AND p.proname LIKE 'oh\_%' LOOP
    EXECUTE format('REVOKE ALL ON FUNCTION %s FROM PUBLIC', f.sig);
    BEGIN EXECUTE format('REVOKE ALL ON FUNCTION %s FROM anon', f.sig); EXCEPTION WHEN undefined_object THEN NULL; END;
    EXECUTE format('GRANT EXECUTE ON FUNCTION %s TO authenticated', f.sig);
    IF f.proname IN ('oh_public_services', 'oh_submit_bite_notice', 'oh_suppress', 'oh_need') THEN EXECUTE format('GRANT EXECUTE ON FUNCTION %s TO anon', f.sig); END IF;
  END LOOP;
END $$;
