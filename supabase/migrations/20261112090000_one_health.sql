RETURNS void LANGUAGE plpgsql SECURITY DEFINER SET search_path = pg_catalog, public AS $$
BEGIN
  PERFORM public.oh_need(public.oh_role_in(p_institution) IN ('lead', 'clinician', 'nurse', 'records', 'lab_scientist', 'coordinator'), 'Only staff of this facility can confirm its services');
