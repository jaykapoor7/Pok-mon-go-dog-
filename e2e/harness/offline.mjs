import { chromium } from "@playwright/test";
import { asMember } from "./harness.mjs";
const OUT = process.argv[2];
const browser = await chromium.launch({ executablePath: process.env.PLAYWRIGHT_CHROMIUM_PATH || undefined });
const ctx = await browser.newContext({ viewport: { width: 390, height: 844 }, reducedMotion: "reduce" });
const { writes } = await asMember(ctx);
const page = await ctx.newPage();
await page.goto("http://localhost:3001/ngo/field", { waitUntil: "networkidle" }); await page.waitForTimeout(2000);
await ctx.setOffline(true); await page.waitForTimeout(300);
await page.locator('.fd-card .btn:has-text("Add a note")').first().click();
await page.fill(".fd-note textarea", "Fed and checked, wound drier (TEST)");
await page.getByRole("button", { name: "Keep as draft" }).click(); await page.waitForTimeout(500);
await page.screenshot({ path: `${OUT}/field-offline.png` });
console.log("offline drafts:", await page.evaluate(() => localStorage.getItem("sp2.field.drafts")), "writes", writes.length);
await ctx.setOffline(false); await page.waitForTimeout(500);
await page.getByRole("button", { name: "Send them now" }).click(); await page.waitForTimeout(1200);
await page.screenshot({ path: `${OUT}/field-sent.png` });
console.log("after:", await page.evaluate(() => localStorage.getItem("sp2.field.drafts")), writes.map((w) => w.fn));
await browser.close();
